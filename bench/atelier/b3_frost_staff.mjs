// B3 서리 지팡이 (16×16 아이템)
// 구조: 왼쪽 아래 → 오른쪽 위 45° 자루(나무 2단 램프) + 오른쪽 위 얼음 결정 3개 묶음(자동 음영 + 깎인 면) + 이음부 금속 묶음.
// 포인트: 차가운 결정(밝음) vs 따뜻한 나무(어둠) 온도 대비, 반짝임 픽셀은 2개만.
import { PixelCanvas, pixelRamp } from '../../atelier/pixel.js';

export default () => {
  const c = new PixelCanvas(16);
  const ice = pixelRamp('#6cc8f0', 5, { spread: 0.1, hueShift: 22 });
  const wood = ['#4a2f1f', '#6e4a2e', '#8f6640'];
  const band = ['#7a8796', '#c9d3dd'];
  // 자루: 중심선 (2,13) → (9,6). 한 행에 [밝음, 어둠] 2픽셀
  for (let t = 0; t <= 7; t++) {
    const x = 2 + t, y = 13 - t;
    c.set(x, y, wood[2]);
    c.set(x + 1, y, wood[0]);
    if (t % 3 === 1) c.set(x, y, wood[1]); // 나뭇결 마디
  }
  c.set(1, 14, wood[0]); c.set(2, 14, wood[1]); // 끝(물미)
  // 결정 3개: 마스크 → 자동 음영
  // v2: 넓은 결정 묶음은 도끼날처럼 보임 → 자루 방향(↗)으로 길쭉한 주 결정 + 양옆으로 갈라지는 작은 결정 둘
  const shards = [
    [[15.4, -0.2], [14.1, 4.1], [10.2, 6.6], [11.3, 2.1]],   // 주 결정: 끝(15,0) → 뿌리(10,6)
    [[8.3, 0.6], [10.3, 3.2], [10, 5.8], [8.1, 3.8]],         // 왼쪽 위로 갈라진 작은 결정
    [[15.6, 7.8], [13.1, 9.1], [11.4, 7.4], [13.8, 6.4]],     // 오른쪽 아래로 갈라진 작은 결정
  ];
  for (const s of shards) {
    const m = new PixelCanvas(16).poly(s, '#fff').mask();
    // r2: 가장 어두운 램프(남색)가 결정 가장자리를 덮어 노이즈처럼 보임 → 밝은 4단만 사용
    c.autoShade(m, ice.slice(1), { light: [-1, -1.3], radius: 2 });
  }
  // 깎인 면: 주 결정 중심선 밝게, 오른쪽 면 한 단계 어둡게
  c.line(14, 1, 11, 4, ice[4]);   // 주 결정 능선(빛 받는 모서리)
  c.set(13, 4, ice[2]); c.set(12, 5, ice[2]); // 반대 면 그림자(한 단계만)
  // 이음부 금속 묶음(결정과 자루를 묶는 띠)
  // r2: 정체불명 가드로 보이던 회색 덩어리 → 자루 축 위 2픽셀 은색 고리로 축소
  c.set(9, 6, band[1]); c.set(10, 6, band[0]);
  // v3: 떠 있는 반짝임에 외곽선이 붙으면 덩어리가 됨 → 외곽선 다음에 찍는다
  // r2: 재질마다 외곽선 색이 달라 산만 → 하나의 짙은 남보라 외곽선으로 통일
  c.outline('#1c1a2b');
  c.set(13, 1, '#ffffff'); // r2: 실루엣 밖에 떠 있던 반짝임(6,3)은 '튀어나온 고립 픽셀'로 읽혀 제거
  return [{ name: 'frost_staff', kind: 'item', canvas: c }];
};
