/** 아이콘 4종: R = 재질 램프 6단(0 외곽선 … 5 밝음), trim = [어둠, 밝음], point = [몸, 반짝임], inner = 안쪽 어둠, light = 공유 빛 */
export function armorIcons({ R, trim, point, inner, light }) {
  const map = { x: trim[0], y: trim[1], g: point[0], h: point[1], i: inner, w: light };
  const out = {};
  for (const [k, rows] of Object.entries(ARMOR_ART)) {
    const c = new PixelCanvas(16);
    rows.forEach((row, y) => {
      if (row.length !== 16) throw new Error(`${k} ${y}행 길이 ${row.length}`);
      [...row].forEach((ch, x) => { if (ch !== '.') c.set(x, y, /[0-5]/.test(ch) ? R[+ch] : map[ch]); });
    });
    out[k] = placeInSlot(c, k);
  }
  return out;
}
